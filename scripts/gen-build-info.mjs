// Generates src/build-info.ts with the current git commit and build time.
// Runs automatically via npm pre-scripts (and postinstall); the output is git-ignored.
import {execSync} from 'node:child_process';
import {writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';

function git(args, fallback) {
  try {
    return execSync(`git ${args}`, {stdio: ['ignore', 'pipe', 'ignore']}).toString().trim() || fallback;
  } catch {
    return fallback;
  }
}

const commit = git('rev-parse HEAD', 'unknown');
const dirty = git('status --porcelain', '') !== '';

const content = `// Auto-generated by scripts/gen-build-info.mjs — do not edit.
export const buildInfo = {
  commit: '${commit}',
  commitShort: '${commit === 'unknown' ? 'unknown' : commit.slice(0, 7)}',
  dirty: ${dirty},
  builtAt: '${new Date().toISOString()}',
};
`;

const target = fileURLToPath(new URL('../src/build-info.ts', import.meta.url));
writeFileSync(target, content);
console.log(`build-info: ${commit.slice(0, 7)}${dirty ? ' (dirty)' : ''}`);
